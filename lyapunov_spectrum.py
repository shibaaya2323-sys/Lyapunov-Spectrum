import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. 計算結果の取得
# ============================================================

lambdas = result["lambdas"]

num_exponents = len(lambdas)

j = np.arange(1, num_exponents + 1)

# ============================================================
# 2. 最終 Lyapunov spectrum
#
# lambda_1, lambda_2, ..., lambda_44
# の最終値をすべて描画
# ============================================================

plt.figure(figsize=(7, 5.5))

# ------------------------------------------------------------
# Lyapunov spectrum
# ------------------------------------------------------------

plt.plot(j,lambdas,marker="o",markersize=4)

# ------------------------------------------------------------
# lambda = 0 の基準線
# ------------------------------------------------------------

plt.axhline(0.0,linewidth=1.0)

# ------------------------------------------------------------
# 軸ラベル
# ------------------------------------------------------------

plt.xlabel(r"$j$")

plt.ylabel(r"$\lambda_j$")

# ------------------------------------------------------------
# タイトル
# ------------------------------------------------------------

plt.title(r"Lyapunov spectrum")

plt.grid()

plt.show()


# ============================================================
# 3. Lyapunov spectrum の前半部分を拡大
#
# j = 1, 2, ..., 30
# を描画する
# ============================================================

num_zoom = min(30, num_exponents)

plt.figure(figsize=(7, 5.5))

# ------------------------------------------------------------
# 前半部分の Lyapunov spectrum
# ------------------------------------------------------------

plt.plot(j[:num_zoom],lambdas[:num_zoom],marker="o",markersize=4)

# ------------------------------------------------------------
# lambda = 0 の基準線
# ------------------------------------------------------------

plt.axhline(0.0,linewidth=1.0)

# ------------------------------------------------------------
# 軸ラベル
# ------------------------------------------------------------

plt.xlabel(r"$j$")

plt.ylabel(r"$\lambda_j$")

# ------------------------------------------------------------
# タイトル
# ------------------------------------------------------------

plt.title(r"Lyapunov spectrum ($j=1,\ldots,30$)")

plt.grid()

plt.show()
