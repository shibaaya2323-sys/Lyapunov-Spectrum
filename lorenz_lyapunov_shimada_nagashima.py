# ============================================================
# 1. パラメータ
# ============================================================

sigma = 16.0
b = 4.0
gamma = 40.0

# 論文の設定
dt = 0.01
tau = 1.0
t_max = 4096.0

steps_per_tau = int(round(tau / dt))

# n_ は NumPy 配列専用とするため、
# 区間数を表す整数には num_ を用いる。
num_tau = int(round(t_max / tau))


# ============================================================
# 2. Lorenz 方程式
#
# dX/dt = -sigma X + sigma Y
# dY/dt = (gamma - Z)X - Y
# dZ/dt = XY - bZ
# ============================================================

@njit
def lorenz(n_x):

    X = n_x[0]
    Y = n_x[1]
    Z = n_x[2]

    n_dx = np.empty(3, dtype=np.float64)

    n_dx[0] = (-sigma * X + sigma * Y)
    n_dx[1] = ((gamma - Z) * X - Y)
    n_dx[2] = (X * Y - b * Z)

    return n_dx


# ============================================================
# 3. Jacobian
#
# 第一変分方程式
#
# d(delta x)/dt
# =
# J(x) delta x
#
# J(x)
# =
# [ -sigma       sigma      0 ]
# [ gamma-Z      -1        -X ]
# [ Y             X        -b ]
# ============================================================

@njit
def jacobian(n_x):

    X = n_x[0]
    Y = n_x[1]
    Z = n_x[2]

    n_J = np.empty((3, 3),dtype=np.float64)

    n_J[0, 0] = -sigma
    n_J[0, 1] = sigma
    n_J[0, 2] = 0.0

    n_J[1, 0] = gamma - Z
    n_J[1, 1] = -1.0
    n_J[1, 2] = -X

    n_J[2, 0] = Y
    n_J[2, 1] = X
    n_J[2, 2] = -b

    return n_J


# ============================================================
# 4. 軌道方程式 + 第一変分方程式
#
# E の各列が
#
# e1, e2, e3
#
# に対応する。
#
# dE/dt = J(x) E
# ============================================================

@njit
def rhs(n_x, n_E):

    n_dx = lorenz(n_x)

    n_J = jacobian(n_x)

    n_dE = n_J @ n_E

    return n_dx, n_dE


# ============================================================
# 5. Runge-Kutta-Gill 法
# ============================================================

sqrt2 = np.sqrt(2.0)

a31 = (sqrt2 - 1.0) / 2.0
a32 = (2.0 - sqrt2) / 2.0

a42 = -sqrt2 / 2.0
a43 = (2.0 + sqrt2) / 2.0

b1 = 1.0 / 6.0
b2 = (2.0 - sqrt2) / 6.0
b3 = (2.0 + sqrt2) / 6.0
b4 = 1.0 / 6.0


@njit
def rkg_step(n_x, n_E, h):

    # --------------------------------------------------------
    # 第1段
    # --------------------------------------------------------

    n_k1x, n_k1E = rhs(n_x,n_E)

    # --------------------------------------------------------
    # 第2段
    # --------------------------------------------------------

    n_x2 = (n_x + 0.5 * h * n_k1x)
    n_E2 = (n_E + 0.5 * h * n_k1E)
    n_k2x, n_k2E = rhs(n_x2,n_E2)

    # --------------------------------------------------------
    # 第3段
    # --------------------------------------------------------

    n_x3 = (n_x + h * (a31 * n_k1x + a32 * n_k2x))
    n_E3 = (n_E + h * (a31 * n_k1E + a32 * n_k2E))
    n_k3x, n_k3E = rhs(n_x3,n_E3)

    # --------------------------------------------------------
    # 第4段
    # --------------------------------------------------------

    n_x4 = (n_x + h * (a42 * n_k2x + a43 * n_k3x))
    n_E4 = (n_E + h * (a42 * n_k2E + a43 * n_k3E))
    n_k4x, n_k4E = rhs(n_x4,n_E4)

    # --------------------------------------------------------
    # 更新
    # --------------------------------------------------------

    n_x_new = (n_x + h * (b1 * n_k1x + b2 * n_k2x + b3 * n_k3x + b4 * n_k4x))
    n_E_new = (n_E + h * (b1 * n_k1E + b2 * n_k2E + b3 * n_k3E + b4 * n_k4E))

    return n_x_new, n_E_new

# ============================================================
# 6. Gram-Schmidt
#
# Appendix A 式 (A.1)
# ============================================================

@njit
def gram_schmidt(n_E):

    # --------------------------------------------------------
    # 1本目
    # --------------------------------------------------------

    n_v1 = n_E[:, 0].copy()
    r1 = np.sqrt(np.dot(n_v1, n_v1))
    n_e1 = n_v1 / r1

    # --------------------------------------------------------
    # 2本目
    # --------------------------------------------------------

    n_v2 = n_E[:, 1].copy()
    n_w2 = (n_v2 - np.dot(n_e1, n_v2) * n_e1)
    r2 = np.sqrt(np.dot(n_w2, n_w2))
    n_e2 = n_w2 / r2

    # --------------------------------------------------------
    # 3本目
    # --------------------------------------------------------

    n_v3 = n_E[:, 2].copy()
    n_w3 = (n_v3 - np.dot(n_e1, n_v3) * n_e1 - np.dot(n_e2, n_v3) * n_e2)
    r3 = np.sqrt(np.dot(n_w3, n_w3))
    n_e3 = n_w3 / r3

    # --------------------------------------------------------
    # 新しい正規直交基底
    # --------------------------------------------------------

    n_E_new = np.empty((3, 3),dtype=np.float64)

    n_E_new[:, 0] = n_e1
    n_E_new[:, 1] = n_e2
    n_E_new[:, 2] = n_e3

    return (
        n_E_new,
        r1,
        r2,
        r3
    )

# ============================================================
# 7. 初期基底の k 次元体積
#
# Case 3 は初期基底が正規直交ではないため、
# Appendix A 式 (A.2) の最初の分母を正しく入れる。
# ============================================================

@njit
def initial_volumes(n_E):

    n_e1 = n_E[:, 0]
    n_e2 = n_E[:, 1]
    n_e3 = n_E[:, 2]

    # --------------------------------------------------------
    # 1次元体積
    # --------------------------------------------------------

    V1 = np.linalg.norm(n_e1)

    # --------------------------------------------------------
    # 2次元体積
    #
    # |e1 × e2|
    # --------------------------------------------------------

    V2 = np.linalg.norm(np.cross(n_e1, n_e2))

    # --------------------------------------------------------
    # 3次元体積
    #
    # |det E|
    # --------------------------------------------------------

    V3 = abs(np.linalg.det(n_E))

    return V1, V2, V3


# ============================================================
# 8. Lyapunov 指数の計算
#
# Appendix A
#
# 式 (A.1)
#   Gram-Schmidt
#
# 式 (A.2)
#   各区間の体積膨張率を蓄積
#
# 計算部分は Numba でコンパイルする。
# ============================================================

@njit
def calculate_lyapunov_core(n_x0,n_basis0):

    # --------------------------------------------------------
    # 初期状態
    # --------------------------------------------------------

    n_x = n_x0.copy()

    # n_basis0 は
    #
    # [e1,
    #  e2,
    #  e3]
    #
    # という「各行が基底ベクトル」の形なので、
    # 転置して各列を基底ベクトルとする。

    n_E = n_basis0.T.copy()

    # --------------------------------------------------------
    # 初期基底の体積
    # --------------------------------------------------------

    V1_0, V2_0, V3_0 = initial_volumes(n_E)

    # --------------------------------------------------------
    # 累積対数
    # --------------------------------------------------------

    sum_log_r1 = 0.0
    sum_log_r12 = 0.0
    sum_log_r123 = 0.0

    # --------------------------------------------------------
    # 保存配列を事前確保
    # --------------------------------------------------------

    n_times = np.empty(num_tau, dtype=np.float64)

    n_lambda_e1 = np.empty(num_tau, dtype=np.float64)
    n_lambda_e2 = np.empty(num_tau, dtype=np.float64)
    n_lambda_e3 = np.empty(num_tau, dtype=np.float64)

    # ========================================================
    # 時間発展
    # ========================================================

    for j in range(num_tau):

        # ----------------------------------------------------
        # tau = 1.0 の間、
        #
        # 軌道方程式
        # +
        # 第一変分方程式
        #
        # を同時積分
        # ----------------------------------------------------

        for _ in range(steps_per_tau):

            n_x, n_E = rkg_step(n_x,n_E,dt)

        # ----------------------------------------------------
        # 現在時刻
        #
        # t = (j + 1) tau
        # ----------------------------------------------------

        t = (j + 1) * tau

        # ----------------------------------------------------
        # Gram-Schmidt
        # ----------------------------------------------------

        (
            n_E,
            r1,
            r2,
            r3
        ) = gram_schmidt(n_E)

        # ----------------------------------------------------
        # log は一度だけ計算
        # ----------------------------------------------------

        log_r1 = np.log(r1)
        log_r2 = np.log(r2)
        log_r3 = np.log(r3)

        # ----------------------------------------------------
        # 最初の区間
        #
        # 初期基底が必ずしも正規直交とは限らないので、
        # Appendix A 式 (A.2) の分母を入れる。
        # ----------------------------------------------------

        if j == 0:

            sum_log_r1 += (log_r1 - np.log(V1_0))

            sum_log_r12 += (log_r1 + log_r2 - np.log(V2_0))

            sum_log_r123 += (log_r1 + log_r2 + log_r3 - np.log(V3_0))

        # ----------------------------------------------------
        # 2回目以降
        #
        # 直前の基底は正規直交基底なので
        #
        # V1 = V2 = V3 = 1
        #
        # である。
        # ----------------------------------------------------

        else:

            sum_log_r1 += log_r1

            sum_log_r12 += (log_r1 + log_r2)

            sum_log_r123 += (log_r1 + log_r2 + log_r3)

        # ----------------------------------------------------
        # 有限時間 k 次元 Lyapunov 指数
        # ----------------------------------------------------

        lambda_e1 = (sum_log_r1 / t)

        lambda_e2 = (sum_log_r12 / t)

        lambda_e3 = (sum_log_r123 / t)

        # ----------------------------------------------------
        # 配列へ保存
        # ----------------------------------------------------

        n_times[j] = t

        n_lambda_e1[j] = lambda_e1
        n_lambda_e2[j] = lambda_e2
        n_lambda_e3[j] = lambda_e3

    return (
        n_times,
        n_lambda_e1,
        n_lambda_e2,
        n_lambda_e3
    )

# ============================================================
# 9. Python 側のラッパー
#
# Numba 内では dictionary を作らず、
# NumPy 配列だけを返す。
#
# 外側で従来と同じ result["t"], result["e1"] ...
# の形に変換する。
# ============================================================

def calculate_lyapunov(n_x0,n_basis0):

    (
        n_times,
        n_lambda_e1,
        n_lambda_e2,
        n_lambda_e3
    ) = calculate_lyapunov_core(
        n_x0,
        n_basis0
    )

    return {

        "t":
            n_times,

        "e1":
            n_lambda_e1,

        "e2":
            n_lambda_e2,

        "e3":
            n_lambda_e3
    }

